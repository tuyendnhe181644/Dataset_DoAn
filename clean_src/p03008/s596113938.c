#include <stdio.h>

int main()
{
	int N, c[2][3];
	scanf("%d", &N);
	scanf("%d %d %d", &(c[0][0]), &(c[0][1]), &(c[0][2]));
	scanf("%d %d %d", &(c[1][0]), &(c[1][1]), &(c[1][2]));
	if (c[0][0] * c[1][1] > c[0][1] * c[1][0]) {
		c[0][0] += c[0][1];
		c[0][1] = c[0][0] - c[0][1];
		c[0][0] -= c[0][1];
		c[1][0] += c[1][1];
		c[1][1] = c[1][0] - c[1][1];
		c[1][0] -= c[1][1];
	}
	if (c[0][1] * c[1][2] > c[0][2] * c[1][1]) {
		c[0][1] += c[0][2];
		c[0][2] = c[0][1] - c[0][2];
		c[0][1] -= c[0][2];
		c[1][1] += c[1][2];
		c[1][2] = c[1][1] - c[1][2];
		c[1][1] -= c[1][2];
	}
	if (c[0][0] * c[1][1] > c[0][1] * c[1][0]) {
		c[0][0] += c[0][1];
		c[0][1] = c[0][0] - c[0][1];
		c[0][0] -= c[0][1];
		c[1][0] += c[1][1];
		c[1][1] = c[1][0] - c[1][1];
		c[1][0] -= c[1][1];
	}
	
	long long g, s, b, max = 0;
	if (c[0][2] < c[1][2]) {
		for (g = N / c[0][0]; g >= 0; g--) {
			for (s = (N - g * c[0][0]) / c[0][1]; s >= 0; s--) {
				b = (N - g * c[0][0] - s * c[0][1]) / c[0][2];
				if (g * (c[1][0] - c[0][0]) + s * (c[1][1] - c[0][1]) + b * (c[1][2] - c[0][2]) + N > max) max = g * (c[1][0] - c[0][0]) + s * (c[1][1] - c[0][1]) + b * (c[1][2] - c[0][2]) + N;
			}
		}
	} else if (c[0][1] < c[1][1]) {
		for (g = N / c[0][0]; g >= 0; g--) {
			s = (N - g * c[0][0]) / c[0][1];
			if (g * (c[1][0] - c[0][0]) + s * (c[1][1] - c[0][1]) + N > max) max = g * (c[1][0] - c[0][0]) + s * (c[1][1] - c[0][1]) + N;
		}
		b = max / c[1][2];
		max += b * (c[0][2] - c[1][2]);
	} else if (c[0][0] < c[1][0]) {
		g = N / c[0][0];
		N += g * (c[1][0] - c[0][0]);
		for (s = N / c[1][1]; s >= 0; s--) {
			b = (N - s * c[1][1]) / c[1][2];
			if (s * (c[0][1] - c[1][1]) + b * (c[0][2] - c[1][2]) + N > max) max = s * (c[0][1] - c[1][1]) + b * (c[0][2] - c[1][2]) + N;
		}
	} else {
		for (g = N / c[1][0]; g >= 0; g--) {
			for (s = (N - g * c[1][0]) / c[1][1]; s >= 0; s--) {
				b = (N - g * c[1][0] - s * c[1][1]) / c[1][2];
				if (g * (c[0][0] - c[1][0]) + s * (c[0][1] - c[1][1]) + b * (c[0][2] - c[1][2]) + N > max) max = g * (c[0][0] - c[1][0]) + s * (c[0][1] - c[1][1]) + b * (c[0][2] - c[1][2]) + N;
			}
		}
	}
	
	printf("%lld\n", max);
	fflush(stdout);
	return 0;
}