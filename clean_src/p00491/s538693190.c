#include<stdio.h>

int main(void)
{
	int i,j,k,N,K,A[101],B[101],dp[101][3][2],d,temp,h,S;
	
	scanf("%d%d",&N,&K);
	d=0;
	S=0;
	for(i=0;i<=K-1;i++) 
	{
		scanf("%d%d",&A[i],&B[i]);
		if(A[i]==1) d=B[i];
	}
	for(i=0;i<=N-1;i++)
	{
		for(j=0;j<=2;j++)
		{
			for(k=0;k<=1;k++)
			{
				dp[i][j][k]=0;
			}
		}
	}
	if(d==0)
	{
		dp[0][0][0]=1;
		dp[0][1][0]=1;
		dp[0][2][0]=1;
		h=0;
	}
	else
	{
		dp[0][d-1][0]=1;
		h=1;
	}
	for(i=0;i<=K-1;i++)
	{
		for(j=0;j<=K-2;j++)
		{
			if(A[j]>A[j+1])
			{
				temp=A[j];
				A[j]=A[j+1];
				A[j+1]=temp;
				temp=B[j];
				B[j]=B[j+1];
				B[j+1]=temp;
			}
		}
	}
	for(i=1;i<=N-1;i++)
	{
		if(A[h]==i+1)
		{
			for(j=0;j<=2;j++)
			{
				if(j!=B[h]-1)
				{
					dp[i][B[h]-1][0]=(dp[i][B[h]-1][0]+dp[i-1][j][0]+dp[i-1][j][1])%10000;
				}
			}
			dp[i][B[h]-1][1]=dp[i-1][B[h]-1][0]%10000;
			h++;
		}
		else
		{
			dp[i][0][0]=(dp[i-1][1][0]+dp[i-1][1][1]+dp[i-1][2][0]+dp[i-1][2][1])%10000;
			dp[i][0][1]=dp[i-1][0][0]%10000;
			dp[i][1][0]=(dp[i-1][0][0]+dp[i-1][0][1]+dp[i-1][2][0]+dp[i-1][2][1])%10000;
			dp[i][1][1]=dp[i-1][1][0]%10000;
			dp[i][2][0]=(dp[i-1][1][0]+dp[i-1][1][1]+dp[i-1][0][0]+dp[i-1][0][1])%10000;
			dp[i][2][1]=dp[i-1][2][0]%10000;
		}
	}
	for(i=0;i<=2;i++)
	{
		for(j=0;j<=1;j++)
		{
			S+=dp[N-1][i][j];
			S%=10000;
		}
	}
	printf("%d\n",S);
	return 0;
}