int Not(int a){
	switch( a ){
		case FALSE:
			return TRUE;
		case UNKNOWN:
			return UNKNOWN;
		case TRUE:
			return FALSE;
	}
	return X;
}

int And(int a, int b){
	if( a == X || b == X ){ return X; }	//?????§?????????
	if( a == FALSE || b == FALSE ){
		return FALSE;
	}else if( a == UNKNOWN || b == UNKNOWN ){
		return UNKNOWN;
	}else if( a == TRUE && b == TRUE ){
		return TRUE;
	}
	return X;
}

int Or(int a, int b){
	if( a == X || b == X ){ return X; }	//?????§?????????
	if( a == TRUE || b == TRUE ){
		return TRUE;
	}else if( a == UNKNOWN || b == UNKNOWN ){
		return UNKNOWN;
	}else if( a == FALSE && b == FALSE ){
		return FALSE;
	}
	return X;
}