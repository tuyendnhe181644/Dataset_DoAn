void bipartite_graph_input(void){
    int a;
    scanf("%d %d %d", &n1, &n2, &m);
    n=n1+n2; // n?????°??????????????°
    for (a = 1; a <= m; a++) {
        scanf("%d %d", &tail[a], &head[a]);
        tail[a]++;
        head[a]++;
        head[a] += n1;
    }
}
void bipartite_incidence_list_construct(void){
    int a, v1;
    for (v1 = 1; v1 <= n1; v1++) edgefirst[v1] = 0;
    for (a = m; a >= 1; a--) {
        v1 = tail[a];
        edgenext[a] = edgefirst[v1];
        edgefirst[v1] = a;
    }
}
