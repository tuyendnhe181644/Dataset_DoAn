                v2 = pathend;   // ??±???????????¢?´¢??¨??§pathend???????????????v1?????§?????????
                a = parent[v2]; // ????????????????????????????????°?????¨?????????????????°????????????
                match[v2] = a;
                w1 = tail[a];
