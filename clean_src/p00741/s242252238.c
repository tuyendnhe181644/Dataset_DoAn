int solve (int W, int H) {
  int i, j;
  int count = 0;
  Coord start;
  stack S = new_stack ();  // ?¨?????????????????????????????????????

  for(i = 0; i <= W; i++){
    for(j = 0; j <= H; j++){
      if(M[j][i] == 1){
	count++;
	M[j][i] = 0;
	start.row = j;
	start.col = i;
	push(S, start);
	// ??¢?´¢
	while (!is_empty(S)) {
	  Coord current = pop(S);                    // pop ???????????????
	  int d;                                     // ??????
	  int D1[]={1,1,0,-1,-1,-1,0,1}; int D2[]={0,1,1,1,0,-1,-1,-1};  // ????????¢?????¶?????¨
	  //printf("?????¨??°??? [%d, %d]\n", current.row, current.col);  // ??¬??\???????????????
	  //display_map(W, H); // ?????¨??????????????¨??? (??¬??\???????????????)
	  for (d=0; d<8; d++) {
	    Coord nc = current;                      // Next Cell
	    // ????????§???????????????
	    nc.row += D1[d]; nc.col += D2[d];

      
	    if(M[nc.row][nc.col] == 1){
	      push(S, nc);
	      M[nc.row][nc.col] = 0;
	    }

	  }
	}
      }
    }
  }
  return count;  
}

