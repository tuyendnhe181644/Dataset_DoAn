m[10001][2];
D[10002][3];
#define min(a,b)((a)<(b)?(a):(b))
#define min3(a,b,c)min(min(a,b),c)
main(n){
	int x,c;
	scanf("%*d");
	for(;~scanf("%d\n",&n);){
		memset(m,0,sizeof(m));
		for(x=0;x<4*n;x++){
			c=getchar();
			m[(x%(2*n)+1)/2][x/(2*n)]|=(c=='Y');
		}
		D[0][0]=-1;
		D[0][1]=0;
		D[0][2]=1;
		for(x=0;x<=n;x++){
			D[x+1][0]=min3(
				D[x][0]+1+(m[x][1]?3:m[x][0]?1:0),
				D[x][1]+1+(m[x][1]?2:1),
				D[x][2]+1+2);
			D[x+1][1]=min3(
				D[x][0]+1+1+(m[x][1]?1:0),
				D[x][1]+1+(m[x][0]?1:0)+(m[x][1]?1:0),
				D[x][2]+1+1+(m[x][0]?1:0));
			D[x+1][2]=min3(
				D[x][0]+1+2,
				D[x][1]+1+(m[x][0]?2:1),
				D[x][2]+1+(m[x][0]?3:m[x][1]?1:0));
		}
		printf("%d\n",D[n+1][0]);
	}
}