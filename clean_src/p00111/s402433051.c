char tr[130];
char buf[250], *p;
char tmp[1050], *tp; int pos;

int getBit(void)
{
	int k;
	static char a[] = { 16, 8, 4, 2, 1 };
	if (!*tp) return -1;
	k = (((*tp) - 1) & a[pos++]) != 0;
	if (pos >= 5) pos = 0, tp++;
	return k;
}

int main()
{
	int i, a, f;

	for (i = 'A'; i <= 'Z'; i++) tr[i] = i - 'A' + 1;
	tr[' '] = 27, tr['.'] = 28, tr[','] = 29, tr['-'] = 30, tr['\''] = 31, tr['?'] = 32;
	while (gets(p = buf) != NULL) {
		tp = tmp;
		//		while (isspace(*p)) p++;
		while (*p) *tp++ = tr[*p++];
		*tp = 0, tp = tmp, pos = 0, f = 1;
		while (f) {
			i = 0;
			while (1) {
				if ((a = getBit()) < 0) { f = 0; break; }
				i = a ? tbl[i].r : tbl[i].l;
				if (tbl[i].c) { putchar(tbl[i].c); break; }
			}
		}
		putchar('\n');
	}
	return 0;
}