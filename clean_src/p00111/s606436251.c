int
main(int argc, char **argv)
{
	char line[200 + 2];
	char bina[200 * 5 + 1];
	const char *s, *t;
	char *u;
	int i;

	while (fgets(line, sizeof(line), stdin) != NULL)
	{
		u = bina;
		for (s = line; *s != '\n' && *s != NUL; ++s)
		{
			for (t = encode[(int)*s]; *t != NUL; ++t, ++u)
				*u = *t;
		}

		*u = NUL;
		s = bina;
		while (*s != NUL)
		{
			int p = 0;
			while (decode[p].zero != -1)
			{
				switch (*s++)
				{
				case '0':
					p = decode[p].zero;
					break;

				case '1':
					p = decode[p].one;
					break;
				}
			}

			putchar(decode[p].c);
			t = s;
			for (i = 0; *t != NUL && i <= 6; ++i, ++t)
			{
				if (*t == '1')
					break;
			}

			if (*t == NUL && i <= 5)
				break;
		}

		putchar('\n');
	}

	return 0;
}