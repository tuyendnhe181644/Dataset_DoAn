#include<stdio.h>
#include<stdlib.h>

#define SET_MAX 5

/* A,B?????????????????????????´?????????????????§??????? */
typedef struct{
	int A;
	int B;
}SET;

/* main??¢??° */
int main(void){
	SET *card[SET_MAX];
	int n[SET_MAX];
	int A_score, B_score, set_cnt, i, j;

	for(i = 0;i < SET_MAX;i++)
		card[i] = NULL;

	/* ??\??????????????????????????? */
	for(set_cnt = 0;set_cnt < 5;set_cnt++){
		scanf("%d", &n[set_cnt]);
		if(n[set_cnt] == 0)break;
		card[set_cnt] = (SET*)malloc(sizeof(SET) * n[set_cnt]);
		if(card[set_cnt] == NULL){
			for(i = 0;i < set_cnt;i++)free(card[i]);
			exit(1);
		}
		for(i = 0;i < n[set_cnt];i++)
			scanf("%d %d", &card[set_cnt][i].A, &card[set_cnt][i].B);
	}

	/* ????????????????????????A,B?????????????¨?????????????????????? */
	for(i = 0;i < set_cnt;i++){
		A_score = B_score = 0;
		for(j = 0;j < n[i];j++){
			if(card[i][j].A > card[i][j].B){
				A_score += card[i][j].A + card[i][j].B;
			}else if(card[i][j].A < card[i][j].B){
				B_score += card[i][j].A + card[i][j].B;
			}else{
				A_score += card[i][j].A;
				B_score += card[i][j].B;
			}
		}

		printf("%d %d\n", A_score, B_score);
	}

	/* ?????¢???????????? */
	for(i = 0;i < set_cnt;i++)
		free(card[i]);

	return 0;
}