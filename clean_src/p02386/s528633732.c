void soroe(int ue,int *saikoro){
  int *copy;
  int i;
  copy=malloc(7*sizeof(int));
  makecopy(saikoro,copy);
  char order[8]="SSSSEEEE";
  for(i=0;i<8;i++){
      if(order[i]=='S'){
        saikoro[2]=copy[1];
        saikoro[6]=copy[2];
        saikoro[5]=copy[6];
        saikoro[1]=copy[5];
        makecopy(saikoro,copy);
      }
      if(order[i]=='N'){
        saikoro[1]=copy[2];
        saikoro[2]=copy[6];
        saikoro[6]=copy[5];
        saikoro[5]=copy[1];
        makecopy(saikoro,copy);
      }
      if(order[i]=='W'){
        saikoro[4]=copy[1];
        saikoro[6]=copy[4];
        saikoro[3]=copy[6];
        saikoro[1]=copy[3];
        makecopy(saikoro,copy);
      }
      if(order[i]=='E'){
        saikoro[1]=copy[4];
        saikoro[4]=copy[6];
        saikoro[6]=copy[3];
        saikoro[3]=copy[1];
        makecopy(saikoro,copy);
      }
      if(saikoro[1]==ue) break;
  }
  free(copy);
}


