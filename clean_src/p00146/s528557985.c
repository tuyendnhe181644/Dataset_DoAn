#include <stdio.h>
#include <string.h>

#define INF 1.0e20
#define ABS(a) ((a)>=0?(a):-(a))
#define MAX 32768

typedef struct { int s, d, v; } T;		// ????????±?????????????????¢???????????±?????°
T tbl[17];

double dp[16][MAX];			// DP????????¨?????????
int w[16][MAX];				// ????????±????????°
int prev[16][MAX][2];		// ???????????????????????????
int ord[16];				// ???????????????????????????????????????????????´???

int main()
{
	int n, i, j, k, ii, lim;
	double x;

	scanf("%d", &n);
	for (i = 0; i < n; i++) scanf("%d%d%d", &tbl[i].s, &tbl[i].d, &tbl[i].v);

	memset(dp, 0, sizeof(dp)); memset(w, 0, sizeof(w));
	for (i = 0; i < n; i++) w[i][1<<i] = tbl[i].v, prev[i][1<<i][0] = prev[i][1<<i][1] = -1;

	lim = 1 << n;
	for (k = 0; k < lim; k++) {
		for (i = 0; i < n; i++) {		// ??´????????????
			for (j = 0; j < n; j++) {	// ??´?????????
				if (i == j || w[j][k] == 0) continue;
				ii = k | (1 << i);
				x = dp[j][k] + (ABS(tbl[i].d - tbl[j].d)*(7+2*w[j][k]))/200.0;
				if (dp[i][ii] == 0 || x < dp[i][ii]) {
					dp[i][ii] = x, w[i][ii] = w[j][k] + tbl[i].v;
					prev[i][ii][0] = j;
					prev[i][ii][1] = k;
				}
			}
		}
	}

	// ???????§???????????????????
	for (x = INF, ii = 0, i = 0; i < n; i++) {
			if (dp[i][lim-1] == 0) continue;
			if (dp[i][lim-1] < x) x = dp[i][lim-1], ii = i;
	}

	// ?????£???????????????
	for (ord[0] = ii, i = ii, j = lim-1, k = 1; k < n; k++) {
		ord[k] = prev[i][j][0];
		     j = prev[i][j][1];
		     i = ord[k];
	}

	// ??????
	printf("%d", tbl[ord[n-1]].s);
	for (i = 1; i < n; i++) printf(" %d", tbl[ord[n-i-1]].s);
	putchar('\n');
	return 0;
}