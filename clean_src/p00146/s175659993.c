#include <stdio.h>
#include <string.h>

#define INF 0x7fffffff
#define MAX 32768

int s[16], d[16], v[16];	// ????????±?????????????????¢???????????±?????°
int dd[16][16];
int dp[16][MAX];			// DP????????¨?????????
int w[16][MAX];				// ????????±????????°
short prev[16][MAX][2];		// ???????????????????????????
int ord[16];				// ???????????????????????????????????????????????´???

int main()
{
	int n, i, j, k, t, ii, lim;
	int x, y;

	scanf("%d", &n);
	for (i = 0; i < n; i++) scanf("%d%d%d", s+i, d+i, v+i);
	for (i = 0; i < n; i++) for (j = i+1; j < n; j++) {
		t = d[i] - d[j]; if (t < 0) t = -t;
		dd[i][j] = dd[j][i] = t;
	}

	memset(prev, -1, sizeof(prev));
	for (ii = 1, i = 0; i < n; i++, ii <<= 1) w[i][ii] = v[i];

	lim = 1 << n;
	for (k = 0; k < lim; k++) {
		for (ii = 1, i = 0; i < n; i++, ii <<= 1) {		// ??´????????????
			if (k & ii) continue;
			t = k | ii;
			for (j = 0; j < n; j++) {	// ??´?????????
				if (i == j || w[j][k] == 0) continue;
				x = dp[j][k] + dd[i][j]*(7+2*w[j][k]);
				if (!dp[i][t] || x < dp[i][t]) {
					dp[i][t] = x, w[i][t] = w[j][k] + v[i];
					prev[i][t][0] = j;
					prev[i][t][1] = k;
				}
			}
		}
	}

	// ???????§???????????????????
	for (x = INF, ii = 0, i = 0; i < n; i++) {
		if ((y = dp[i][lim-1]) > 0 && y < x) x = y, ii = i;
	}

	// ?????£???????????????
	for (ord[0] = ii, i = ii, j = lim-1, k = 1; k < n; k++) {
		ord[k] = prev[i][j][0];
		     j = prev[i][j][1];
		     i = ord[k];
	}

	// ??????
	printf("%d", s[ord[n-1]]);
	for (i = 1; i < n; i++) printf(" %d", s[ord[n-i-1]]);
	putchar('\n');
	return 0;
}