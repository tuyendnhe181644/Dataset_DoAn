#include<stdio.h>
#include<math.h>
#include<string.h>
int main()
{
  int bc[6][6]={0},cc[6][6];
  int H,W,K,i,j,i1,j1,ic,jc,i2,j2,minu,sto=0,ans=0;
  char s[7];
  scanf("%d %d %d\n ",&H,&W,&K);
  for(i=0;i<H;i++){
    scanf("%s",s);
    for(j=0;j<W;j++){
     if(s[j]=='#'){
      bc[i][j]=1;
      sto++; 
     }
    }
  }
  
  for(i=0;i<pow(2,H);i++){
    for(j=0;j<pow(2,W);j++){
      for(i1=0;i1<H;i1++){
        for(j1=0;j1<W;j1++){
         cc[i1][j1]=bc[i1][j1]; 
        }
      }
      ic=i;
      jc=j;
      minu=0;
      if(ic/(int)pow(2,5)){
       ic-=pow(2,5);
       for(j2=0;j2<W;j2++){
        if(cc[5][j2]){
         cc[5][j2]=0;
         minu++;
        }
       }
      }
      if(ic/(int)(pow(2,4))==1){
       ic-=pow(2,4);
       for(j2=0;j2<W;j2++){
        if(cc[4][j2]){
         cc[4][j2]=0;
         minu++;
        }
       }
      }
      if(ic/(int)(pow(2,3))==1){
       ic-=pow(2,3);
       for(j2=0;j2<W;j2++){
        if(cc[3][j2]){
         cc[3][j2]=0;
         minu++;
        }
       }
      }
      if(ic/(int)(pow(2,2))==1){
       ic-=pow(2,2);
       for(j2=0;j2<W;j2++){
        if(cc[2][j2]){
         cc[2][j2]=0;
         minu++;
        }
       }
      }
      if(ic/(int)(pow(2,1))==1){
       ic-=pow(2,1);
       for(j2=0;j2<W;j2++){
        if(cc[1][j2]){
         cc[1][j2]=0;
         minu++;
        }
       }
      }
      if(ic/(int)(pow(2,0))==1){
       for(j2=0;j2<W;j2++){
        if(cc[0][j2]){
         cc[0][j2]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,5))==1){
       jc-=pow(2,5);
       for(j2=0;j2<H;j2++){
        if(cc[j2][5]){
         cc[j2][5]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,4))==1){
       jc-=pow(2,4);
       for(j2=0;j2<H;j2++){
        if(cc[j2][4]){
         cc[j2][4]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,3))==1){
       jc-=pow(2,3);
       for(j2=0;j2<H;j2++){
        if(cc[j2][3]){
         cc[j2][3]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,2))==1){
       jc-=pow(2,2);
       for(j2=0;j2<H;j2++){
        if(cc[j2][2]){
         cc[j2][2]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,1))==1){
       jc-=pow(2,1);
       for(j2=0;j2<H;j2++){
        if(cc[j2][1]){
         cc[j2][1]=0;
         minu++;
        }
       }
      }
      if(jc/(int)(pow(2,0))==1){
       for(j2=0;j2<H;j2++){
        if(cc[j2][0]){
         cc[j2][0]=0;
         minu++;
        }
       }
      }

      if((sto-minu)==K)
        ans++;
    }
  }
  printf("%d",ans);
  return 0;
}
