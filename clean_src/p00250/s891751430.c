#include <stdio.h>

int main(void) {
	int n, m;
	
	while (scanf("%d%d", &n, &m), n) {
		int i, j, max = 0;
		int l[100000], r[100000];
		
		long long s = 0;
		long long ss = 0;
		
		l[0] = 0;
		r[0] = 0;

		for (i = 1; i < m; ++i) {
			l[i] = 30001; // ??????????????????
			r[i] = -1;    // ??????????????????
		}
		
		for (i = 1; i <= n; ++i) {
			unsigned int t;
			scanf("%u", &t);
			s = (s + t) % m;
			ss += t;
			
			l[s] = i < l[s] ? i : l[s]; // ??????
			r[s] = i > r[s] ? i : r[s]; // ??????
			
			max = max < s ? s : max;
		}
		
		if (ss < m) {
			printf("%d\n", (int)ss);
			continue;
		}
		
		// ????????????????????°???
		for (i = 1; i < m; ++i) {
			if (r[i] <= 0) {
				continue;
			}
			
			// ??????????????????????????´(i+1)????????°???
			for (j = 1; j < m - max; ++j) {
				// ?????´????????¢???????????°???????????´??°
				if (l[i + j] < r[i]) {
					max = m - j;
					break;
				}
			}
		}

		printf("%d\n", max);
	}
	
	return 0;
}