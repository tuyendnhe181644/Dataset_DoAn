int maxBits(unsigned *a, int len)
{
	int i, k, n, p, l, m, r;
	unsigned *e = a + len;
	k = p = 0;
	while (a < e) {
        if (!*a) { if (p > k) k = p; p = 0; }
        else if (*a == 0xffffffffU) p += 32;
        else {
            for (i = 24; i >= 0; i -= 8) {
                n = ((*a) >> i) & 0xff;
                l = lt[n], m = mt[n], r = rt[n];
                if (l == 8) p += 8;
                else {
                    if (m > k) k = m;
                    p += l; if (p > k) k = p; p = r;
                }
            }
		}
		a++;
	}
	if (p > k) k = p;
	return k;
}

