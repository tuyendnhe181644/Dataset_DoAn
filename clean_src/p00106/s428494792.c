#include<stdio.h>
int main(){
int dp[60][60],i,j,a[60],b[60],c[60],d[60],n,k;
for(i=0;i<55;i++){
for(j=0;j<55;j++){
if(j==0){
dp[i][j]=0;
}
else{
dp[i][j]=100000000;
}
}
}
for(i=0;i<=50;i++){
a[i]=100000,b[i]=100000,c[i]=100000;
}
a[2]=380;
for(i=4;i<=50;i=i+2){
a[i]=a[i-2]+380;
if(i%5==0){
k=i/2;
a[i]=k*380*0.8;
}
}
b[3]=550;
for(i=6;i<=50;i=i+3){
b[i]=b[i-3]+550;
if(i%4==0){
k=i/3;
b[i]=k*550*0.85;
}
}
c[5]=850;
for(i=10;i<=50;i=i+5){
c[i]=c[i-5]+850;
if(i%3==0){
k=i/5;
c[i]=k*850*0.88;
}
}
for(i=0;i<=50;i++){
d[i]=a[i];
}
for(i=0;i<=50;i++){
if(b[i]<d[i]){
d[i]=b[i];
}
}
for(i=0;i<=50;i++){
if(c[i]<d[i]){
d[i]=c[i];
}
}
for(i=1;i<=50;i++){
for(j=1;j<=50;j++){
if(j<i){
dp[i][j]=dp[i-1][j];
}
else{
if(dp[i-1][j]<dp[i-1][j-i]+d[i]){
dp[i][j]=dp[i-1][j];
}
else{
dp[i][j]=dp[i-1][j-i]+d[i];
}
}
}
}
while(1){
scanf("%d\n",&n);
if(n==0){
break;
}
n=n/100;
printf("%d\n",dp[50][n]);
}
return 0;
}
