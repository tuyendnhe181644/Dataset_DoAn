void prime_factor(int n)
{
  int i, d, sw;
  int *pp;

  size = 0;
  if ((n & 1) == 0) {
    do n >>= 1, factor[size++] = 2;
    while ((n & 1) == 0);
  }
  for (pp = ptbl; n > 1 && *pp > 0; pp++) {
    if (n % *pp) continue;
    d = *pp;
    do n /= d, factor[size++] = d;
    while (n % d == 0);
  }
  if (n > 1) {
    int b = (int)sqrt(n);
    for (i = 1009, sw = 0; n > 1; ) {
      if (i > b) {
        factor[size++] = n;
        break;
      }
      if (n % i == 0) {
        do n /= i, factor[size++] = i;
        while (n % i == 0);
      }
      if (sw) { i += 2, sw = 0; }
      else    { i += 4, sw = 1; }
    }
  }
}

