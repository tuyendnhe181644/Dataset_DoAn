#include <stdio.h>

int main(){
	int i, j, S;
	int X[3][3];
	for(i = 0; i < 3; i++){
		for(j = 0; j < 3; j++){
			X[i][j] = -1;
		}
	}
	scanf("%d%d%d", &X[0][0], &X[0][1], &X[1][1]);
	for(S = -100000; S <= 100000; S++){
		X[0][2] = S - X[0][0] - X[0][1];
		X[2][0] = S - X[0][2] - X[1][1];
		X[2][2] = S - X[0][0] - X[1][1];
		X[1][0] = S - X[0][0] - X[2][0];
		X[1][2] = S - X[0][2] - X[2][2];
		X[2][1] = S - X[0][1] - X[1][1];
		if(X[1][0] + X[1][1] + X[1][2] == S && X[2][0] + X[2][1] + X[2][2] == S){
			for(i = 0; i < 3; i++){
				for(j = 0; j < 3; j++){
					printf("%d ", X[i][j]);
				}
				printf("\n");
			}
			return 0;
		}
	}
}