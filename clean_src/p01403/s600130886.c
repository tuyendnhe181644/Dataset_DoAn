#include <stdio.h>

#define MAX	 1000000
int phi[MAX+1];			// ??????????????¢??°??????
char isprime[MAX+1];	// ?´???°????????¨
long long fn[MAX+1];	// ??¬?????????Farey Sequence

void euler_phi()
{
	int i, j;

	for (i = 0; i <= MAX; i++) {
		phi[i] = i;
//		isprime[i] = 0;
	}
	phi[2] = 1;
	for (j = 4; j <= MAX; j += 2) isprime[j] = 1, phi[j] -= phi[j] >> 1;
	for (i = 3; i <= MAX; i++) {
		if (isprime[i]) continue;
		phi[i] -= phi[i] / i;
	    for (j = i+i; j <= MAX; j+=i) isprime[j] = 1, phi[j] -= phi[j] / i;
	}
}

int main()
{
	int t, n;

	euler_phi();
	fn[0] = 1; for (n = 1; n <= MAX; n++) fn[n] = fn[n-1] + phi[n];

	scanf("%d", &t);
	while (t-- > 0) {
		scanf("%d", &n);
		printf("%lld\n", fn[n]);
	}
	return 0;
}