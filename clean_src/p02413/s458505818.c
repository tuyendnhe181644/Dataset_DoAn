/* ????????¨???????¨????????´? */
int sum_per_row(int line_array[], short elem_cnt)
{
	short ii;
	int sum = 0;
	for( ii = 0; ii < elem_cnt; ii++ )
	{
		if( 0 > line_array[ii] )
		{
			continue;
		}
		sum += line_array[ii];
	}
	return sum;
}