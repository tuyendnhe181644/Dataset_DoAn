#include<stdio.h>
#include<stdlib.h>
#define MAX_N 101

struct TEdge{
  int a,b,w;
};

typedef struct TEdge Edge;

Edge *edge;

int par[MAX_N];
int rank[MAX_N];

//Union Find Tree?????????????????????
