#include<stdio.h>
int main(void){
	int num_elements,m,bit[15],temp_val[15],idx,j,k,tgt[15],tgb[15],sw,bitsum=0,tgsum=0;
	scanf("%d %d",&num_elements,&m);
	for(idx=0;idx<num_elements;idx++){
		scanf("%d",&bit[idx]);
		temp_val[idx]=bit[idx];
		bitsum+=bit[idx];
	}
	for(idx=0;idx<m;idx++){
		scanf("%d",&tgt[idx]);
	}
	idx=j=k=0;
	sw=0;
	while(1){
		if(sw%2==0){
			tgb[k]=0;
		}
		else{
			tgb[k]=1;
			tgsum++;
		}
		k++;
		idx++;
		if(idx==tgt[j]){
			j++;
			sw++;
			idx=0;
		}
		if(j==m){
			break;
		}
	}
	//0start
	int zero=0;
	if(bitsum==tgsum){
		while(1){
			sw=0;
			for(idx=0;idx<num_elements;idx++){
				if(tgb[idx]!=temp_val[idx]){
					sw++;
					break;
				}
			}
			if(sw==0){
				break;
			}
			for(idx=0;idx<num_elements;idx++){
				if(tgb[idx]!=temp_val[idx]){
					k=idx;
					break;
				}
			}
			for(idx=k+1;idx<num_elements;idx++){
				if(temp_val[k]!=temp_val[idx]){
					zero+=idx-k;
					j=temp_val[k];
					temp_val[k]=temp_val[idx];
					temp_val[idx]=j;
					break;
				}
			}
		}
	}
	else{
		zero=1000000;
	}
	for(idx=0;idx<num_elements;idx++){
		if(tgb[idx]==1){
			tgb[idx]=0;
		}
		else{
			tgb[idx]=1;
		}
	}
	for(idx=0;idx<num_elements;idx++){
		temp_val[idx]=bit[idx];
	}
	//1start
	int one=0;
	tgsum=num_elements-tgsum;
	if(bitsum==tgsum){
		while(1){
			sw=0;
			for(idx=0;idx<num_elements;idx++){
				if(tgb[idx]!=temp_val[idx]){
					sw++;
					break;
				}
			}
			if(sw==0){
				break;
			}
			for(idx=0;idx<num_elements;idx++){
				if(tgb[idx]!=temp_val[idx]){
					k=idx;
					break;
				}
			}
			for(idx=k+1;idx<num_elements;idx++){
				if(temp_val[k]!=temp_val[idx]){
					one+=idx-k;
					j=temp_val[k];
					temp_val[k]=temp_val[idx];
					temp_val[idx]=j;
					break;
				}
			}
		}
	}
	else{
		one=1000000;
	}
	if(one>zero){
		printf("%d\n",zero);
	}
	else{
		printf("%d\n",one);
	}
	return 0;
}